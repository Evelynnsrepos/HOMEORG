/**
 * Turns the USDA FSIS FoodKeeper data into the table the app ships with.
 *
 *   node scripts/import-foodkeeper.js [path/to/foodkeeper.json]
 *
 * Source: FSIS FoodKeeper Data (https://catalog.data.gov/dataset/fsis-foodkeeper-data),
 * released CC0 by the US Department of Agriculture. The raw file lives in
 * scripts/data/ so the conversion can be repeated when FSIS updates it.
 *
 * Per product and per shelf it takes, in order, the time from purchase, the
 * plain storage time and the time after opening — the low end of each range,
 * because the app would rather nudge early. "Indefinitely" keeps; "Not
 * recommended" means use it the same day; "Package use-by date" and "When
 * ripe" say nothing about days and are left out.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = process.argv[2] || path.join(__dirname, 'data', 'foodkeeper.json');
const OUT = path.join(ROOT, 'src', 'data', 'foodkeeper.ts');

const raw = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const sheet = (name) =>
  raw.sheets.find((s) => s.name === name).data.map((row) => Object.assign({}, ...row));

const versions = sheet('Version');
const version = versions[versions.length - 1].Data_Version_Number;
const categories = new Map(sheet('Category').map((c) => [c.ID, [c.Category_Name, c.Subcategory_Name].filter(Boolean).join(' / ')]));

const UNIT = { Hours: 0, Days: 1, Weeks: 7, Months: 30, Year: 365, Years: 365 };

/** days, 'k' for keeps, or undefined when the source says nothing usable */
function days(p, prefix) {
  const metric = p[`${prefix}_Metric`];
  if (!metric) return undefined;
  if (metric === 'Indefinitely') return 'k';
  if (metric === 'Not Recommended') return 0;
  if (!(metric in UNIT) || p[`${prefix}_Min`] == null) return undefined;
  return Math.round(p[`${prefix}_Min`] * UNIT[metric]);
}
const first = (p, prefixes) => {
  for (const pre of prefixes) {
    const d = days(p, pre);
    if (d !== undefined) return d;
  }
  return undefined;
};

// words that say how something is cut or packed, not what it is
const NOISE = new Set(
  'raw,fresh,cooked,whole,cut,cubes,cube,loose,blend,blends,stuffed,opened,unopened,commercial,homemade,home,made,store,bought,package,packaged,canned,jar,bottled,dry,dried,frozen,refrigerated,shelf,stable,sliced,slices,piece,pieces,mix,mixes,product,products,type,types,other,leftover,leftovers,plain,regular,large,small,chops,chop,steaks,steak,roast,roasts,ground,patties,breast,breasts'.split(','),
);

const entries = [];
for (const p of sheet('Product')) {
  if (!p.Name) continue;
  const fridge = first(p, ['DOP_Refrigerate', 'Refrigerate', 'Refrigerate_After_Opening']);
  const freezer = first(p, ['DOP_Freeze', 'Freeze']);
  const pantry = first(p, ['DOP_Pantry', 'Pantry', 'Pantry_After_Opening']);
  if (fridge === undefined && freezer === undefined && pantry === undefined) continue;
  const words = new Set();
  for (const k of [p.Name, ...(p.Keywords || '').split(',')]) {
    const w = String(k).toLowerCase().replace(/[^a-z0-9 '-]+/g, ' ').replace(/\s+/g, ' ').trim();
    if (w.length >= 3 && !NOISE.has(w)) words.add(w);
  }
  if (!words.size) continue;
  const name = [p.Name, p.Name_subtitle].filter(Boolean).join(', ');
  const enc = (d) => (d === undefined ? 'null' : d === 'k' ? "'k'" : String(d));
  entries.push(
    `  [${JSON.stringify(name)}, ${JSON.stringify([...words])}, ${enc(fridge)}, ${enc(freezer)}, ${enc(pantry)}, ${JSON.stringify(categories.get(p.Category_ID) || '')}],`,
  );
}

const out = `/**
 * GENERATED by scripts/import-foodkeeper.js — do not edit by hand.
 *
 * USDA FSIS FoodKeeper data, version ${version}, released CC0 (public domain)
 * by the US Department of Agriculture: https://catalog.data.gov/dataset/fsis-foodkeeper-data
 *
 * Each row: [name, keywords, fridge, freezer, pantry, category]. Days on that
 * shelf; 'k' keeps; null means FoodKeeper has no number for it.
 */
export const FOODKEEPER_VERSION = ${JSON.stringify(String(version))};

export type FkDays = number | 'k' | null;
export type FkRow = [string, string[], FkDays, FkDays, FkDays, string];

export const foodkeeper: FkRow[] = [
${entries.join('\n')}
];
`;
fs.writeFileSync(OUT, out);
console.log(`${entries.length} products → ${path.relative(ROOT, OUT)} (FoodKeeper ${version})`);
